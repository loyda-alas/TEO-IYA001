; CALCULA EL PRECIO DE 3 PRODUCTOS A, B Y C SI EL PRECIO ES MAYOR A 30 DA UN DESCUENTO DE 5

inicio:

; ASIGNAMOS EL PRECIO AL PRODUCTO A 
    MOV A, 15
; ASIGNAMOS EL PRECIO AL PRODUCTO B Y LO SUMAMOS CON EL PRECIO DEL PRODUCTO A
    MOV B, 15
    ADD A, B
; ASIGNAMOS EL PRECIO DEL PRODUCTO C Y LO SUMAMOS CON LO QUE VA DEL PRODUCTO A
    MOV C, 8
    ADD A, C

; HACEMOS LA COMPARACIÓN PARA SABER SI EL PRODUCTO ES MAYOR O IGUAL A 30 Y DAR EL DESCUENTO O NO
    CMP A, 30
    JAE descuento
    JMP mostrar

; SI LA CONDICIÓN ANTERIOR ES VERDADERA RESTAMOS 5 AL PRECIO
descuento:
    SUB A, 5

mostrar:
    MOV B, 0

; METODO PARA CALCULAR EL VALOR DE DECENAS DEL PRECIO EN CODIGO ASCII
decenas:
    CMP A, 10
    JB unidades
    SUB A, 10
    INC B
    JMP decenas

; METODO PARA CALCULAR EL VALOR DE UNIDADES DEL PRECIO CODIGO ASCII
unidades:
    ADD B, 48
    MOV D, 232
    MOV [D], B
    INC D

    ADD A, 48
    MOV [D], A

fin:
    HLT